// Command redisgen writes internal/decode/redis_commands.go from Valkey's
// command definitions (src/commands/*.json in a Valkey checkout), so the
// Redis classifier's table follows the server's own flags.
//
//	go run ./tools/redisgen -src ~/valkey -commit $(git -C ~/valkey rev-parse --short HEAD) -o internal/decode/redis_commands.go
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"
)

type command struct {
	Container    string   `json:"container"`
	CommandFlags []string `json:"command_flags"`
	ACL          []string `json:"acl_categories"`
	KeySpecs     []struct {
		Flags []string `json:"flags"`
	} `json:"key_specs"`
}

func main() {
	src := flag.String("src", "", "Valkey checkout")
	commit := flag.String("commit", "", "Valkey commit, recorded in the output")
	out := flag.String("o", "", "output file")
	flag.Parse()
	if *src == "" || *out == "" || *commit == "" {
		log.Fatal("usage: redisgen -src DIR -commit SHA -o FILE")
	}
	files, err := filepath.Glob(filepath.Join(*src, "src", "commands", "*.json"))
	if err != nil || len(files) == 0 {
		log.Fatalf("no command files under %s/src/commands", *src)
	}
	type row struct {
		name                                  string
		write, readOnly, admin, dangerous, rm bool
	}
	var rows []row
	containers := map[string]bool{}
	for _, f := range files {
		data, err := os.ReadFile(f)
		if err != nil {
			log.Fatal(err)
		}
		var doc map[string]command
		if err := json.Unmarshal(data, &doc); err != nil {
			log.Fatalf("%s: %v", f, err)
		}
		for name, c := range doc {
			if slices.Contains(c.CommandFlags, "ONLY_SENTINEL") {
				continue
			}
			full := strings.ToUpper(name)
			if c.Container != "" {
				full = strings.ToUpper(c.Container) + " " + full
				containers[strings.ToUpper(c.Container)] = true
			}
			r := row{name: full,
				write:     slices.Contains(c.CommandFlags, "WRITE"),
				readOnly:  slices.Contains(c.CommandFlags, "READONLY"),
				admin:     slices.Contains(c.CommandFlags, "ADMIN"),
				dangerous: slices.Contains(c.ACL, "DANGEROUS"),
			}
			for _, k := range c.KeySpecs {
				if slices.Contains(k.Flags, "RM") || slices.Contains(k.Flags, "DELETE") {
					r.rm = true
				}
			}
			rows = append(rows, r)
		}
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].name < rows[j].name })
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/redisgen from Valkey %s src/commands; DO NOT EDIT.\n\n", *commit)
	b.WriteString("package decode\n\n")
	fmt.Fprintf(&b, "// redisTableSource is the Valkey commit redisCommands was generated from.\nconst redisTableSource = %q\n\n", *commit)
	b.WriteString("// redisContainers are commands whose first argument is a subcommand.\nvar redisContainers = map[string]bool{\n")
	var cs []string
	for c := range containers {
		cs = append(cs, c)
	}
	sort.Strings(cs)
	for _, c := range cs {
		fmt.Fprintf(&b, "\t%q: true,\n", c)
	}
	b.WriteString("}\n\n// redisCommands holds each command's flags: \"CONTAINER SUB\" for subcommands.\nvar redisCommands = map[string]redisFlags{\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "\t%q: {write: %v, readOnly: %v, admin: %v, dangerous: %v, removes: %v},\n", r.name, r.write, r.readOnly, r.admin, r.dangerous, r.rm)
	}
	b.WriteString("}\n")
	src2, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src2, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%d commands, %d containers\n", len(rows), len(cs))
}

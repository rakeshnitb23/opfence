// OpenShellSchemaChecked is when the OpenShell policy schema reference
// (https://docs.nvidia.com/openshell/how-it-works/policies/schema) was last
// compared with this exporter's output.
const OpenShellSchemaChecked = "2026-10-16"

// OpenShell writes one OpenShell network policy per provider for env.
//
// OpenShell can allow or deny, not ask. Operations Opfence allows become
// allow rules; operations it denies become deny rules; operations it would
// ask about are left out of the allow-list, so OpenShell's own policy
// proposal flow puts them to a human. Where a broad allow rule (every
// GraphQL query, every GET) would also cover an operation Opfence asks
// about, OpenShell has no way to carve out an "ask", so the export denies
// that operation instead and says so in a comment.
func OpenShell(c *catalog.Catalog, p *policy.Effective, env string) ([]byte, error) {
	if p == nil {
		p = policy.Resolve(nil, nil)
	}
	policies := mapping()
	var skipped []string
	for _, prov := range c.Providers {
		if prov.SigV4 {
			skipped = append(skipped, prov.ID)
			continue
		}
		key := "opfence_" + strings.ReplaceAll(prov.ID, "-", "_")
		np := mapping()
		addPair(np, "name", scalar(key))
		eps := seq()
		for _, host := range prov.Hosts {
			eps.Content = append(eps.Content, openShellEndpoints(p, prov, host, env)...)
		}
		addPair(np, "endpoints", eps)
		k := scalar(key)
		k.HeadComment = fmt.Sprintf("%s: %d catalog rules, decisions for %s", prov.Title, len(sortedRules(p, prov)), env)
		policies.Content = append(policies.Content, k, np)
	}
	root := mapping()
	addPair(root, "version", &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!int", Value: "1"})
	addPair(root, "network_policies", policies)
	root.HeadComment = strings.Join([]string{
		"Generated by `opfence export --target openshell --environment " + env + "`.",
		"Merge network_policies into your sandbox policy. Checked against the OpenShell",
		"policy schema reference on " + OpenShellSchemaChecked + "; run `openshell policy validate` after merging.",
	}, "\n")
	if len(skipped) > 0 {
		root.FootComment = "Not exported: " + strings.Join(skipped, ", ") + ". AWS Query and JSON actions travel in the request body\n" +
			"or the X-Amz-Target header, which OpenShell's REST matchers cannot see; use `opfence run` for them."
	}
	doc := &yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{root}}
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func openShellEndpoints(p *policy.Effective, prov *catalog.Provider, host, env string) []*yaml.Node {
	rules := sortedRules(p, prov)
	var out []*yaml.Node
	switch {
	case prov.MCP != nil:
		for _, path := range mcpPaths(prov) {
			out = append(out, mcpEndpoint(p, rules, host, path, env))
		}
	case slices.Contains(prov.Git, host):
		out = append(out, gitEndpoint(p, prov, rules, host, env))
	default:
		var closed []string // GraphQL paths with nothing to allow
		for _, path := range prov.GraphQL {
			if ep := graphQLEndpoint(p, prov, rules, host, path, env); ep != nil {
				out = append(out, ep)
			} else {
				closed = append(closed, path)
			}
		}
		if hasREST(prov, rules) {
			out = append(out, restEndpoint(p, prov, rules, host, env, closed))
		}
	}
	return out
}

// mcpPaths is where an MCP provider's streamable HTTP endpoint lives. The
// catalog does not record it yet; every hosted server in it uses /mcp.
func mcpPaths(*catalog.Provider) []string { return []string{"/mcp"} }

func hasREST(prov *catalog.Provider, rules []*catalog.Rule) bool {
	if prov.Defaults.RESTSafeMethods != "" {
		return true
	}
	for _, r := range rules {
		if r.Match.REST != nil {
			return true
		}
	}
	return false
}

func endpointHead(host, path, protocol string) *yaml.Node {
	ep := mapping()
	addPair(ep, "host", scalar(host))
	addPair(ep, "port", &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!int", Value: "443"})
	if path != "" {
		addPair(ep, "path", scalar(path))
	}
	addPair(ep, "protocol", scalar(protocol))
	addPair(ep, "enforcement", scalar("enforce"))
	return ep
}

func graphQLEndpoint(p *policy.Effective, prov *catalog.Provider, rules []*catalog.Rule, host, path, env string) *yaml.Node {
	ep := endpointHead(host, path, "graphql")
	allow, deny := seq(), seq()
	byType := map[string]*[3][]string{} // type -> allowed, denied, ask-but-denied
	notes := map[string][]string{}
	for _, r := range rules {
		m := r.Match.GraphQL
		if m == nil {
			continue
		}
		b := byType[m.Type]
		if b == nil {
			b = &[3][]string{}
			byType[m.Type] = b
		}
		switch d := Ceiling(p, r, env); {
		case d == classes.Allow:
			b[0] = append(b[0], m.Field)
		case d == classes.Deny:
			b[1] = append(b[1], m.Field)
			if n := argNote(p, r, env); n != "" {
				notes[m.Type] = append(notes[m.Type], n)
			}
		default:
			b[2] = append(b[2], m.Field)
		}
	}
	// With secret fields, any query might select one, which OpenShell
	// cannot see.
	queryDefault := prov.Defaults.GraphQLQuery != "" && DefaultDecision(p, prov.Defaults.GraphQLQuery, env) == classes.Allow &&
		(len(prov.Defaults.GraphQLSecretFields) == 0 || DefaultDecision(p, classes.Credential, env) == classes.Allow)
	for _, t := range []string{"query", "mutation", "subscription"} {
		b := byType[t]
		if b == nil {
			b = &[3][]string{}
		}
		denied := b[1]
		comment := strings.Join(notes[t], "\n")
		if t == "query" && queryDefault {
			allow.Content = append(allow.Content, allowRule(pairs("operation_type", scalar(t))))
			if len(b[2]) > 0 {
				denied = append(denied, b[2]...)
				ask := "Opfence would ask about " + strings.Join(b[2], ", ") + "; OpenShell cannot ask inside an allowed\n" +
					"operation type, so these fields are denied here."
				comment = strings.TrimPrefix(comment+"\n"+ask, "\n")
			}
		} else if len(b[0]) > 0 {
			allow.Content = append(allow.Content, allowRule(pairs("operation_type", scalar(t), "fields", flowSeq(b[0]))))
		}
		if len(denied) > 0 {
			rule := pairs("operation_type", scalar(t), "fields", flowSeq(denied))
			rule.HeadComment = comment
			deny.Content = append(deny.Content, rule)
		}
	}
	if len(allow.Content) == 0 {
		// OpenShell needs allow rules on a GraphQL endpoint; leaving the
		// endpoint out blocks it all.
		return nil
	}
	addRules(ep, allow, deny)
	return ep
}

func restEndpoint(p *policy.Effective, prov *catalog.Provider, rules []*catalog.Rule, host, env string, closedGraphQL []string) *yaml.Node {
	ep := endpointHead(host, "", "rest")
	allow, deny := seq(), seq()
	safeDefault := prov.Defaults.RESTSafeMethods != "" && DefaultDecision(p, prov.Defaults.RESTSafeMethods, env) == classes.Allow
	if safeDefault {
		for _, m := range []string{"GET", "HEAD", "OPTIONS"} {
			allow.Content = append(allow.Content, allowRule(pairs("method", scalar(m), "path", scalar("/**"))))
		}
		for _, path := range closedGraphQL {
			// GraphQL also runs queries sent with GET.
			rule := pairs("method", scalar("GET"), "path", scalar(path))
			rule.HeadComment = "GraphQL at " + path + " has nothing OpenShell can allow (any query may select a secret field), so\nqueries sent with GET are denied too."
			deny.Content = append(deny.Content, rule)
		}
	}
	type restRule struct {
		r      *catalog.Rule
		method string
		glob   string
		d      classes.Decision
	}
	var all []restRule
	for _, r := range rules {
		if m := r.Match.REST; m != nil {
			all = append(all, restRule{r, m.Method, templateGlob(m.Path), Ceiling(p, r, env)})
		}
	}
	// coveredByAllow reports which allow rule, if any, would also let x through.
	coveredByAllow := func(x restRule) string {
		if safeDefault && (x.method == "GET" || x.method == "HEAD" || x.method == "OPTIONS") {
			return "the " + x.method + " allow rule above"
		}
		for _, a := range all {
			if a.d == classes.Allow && a.method == x.method && globsOverlap(a.glob, x.glob) {
				return "the allow rule for " + a.r.ID
			}
		}
		return ""
	}
	for _, x := range all {
		rule := pairs("method", scalar(x.method), "path", scalar(x.glob))
		switch {
		case x.d == classes.Allow:
			if coveredByAllowDefault := safeDefault && (x.method == "GET" || x.method == "HEAD" || x.method == "OPTIONS"); !coveredByAllowDefault {
				allow.Content = append(allow.Content, allowRule(rule))
			}
		case x.d == classes.Deny:
			rule = pairs("method", scalar(x.method), "path", scalar(denyGlob(x.glob)))
			rule.HeadComment = argNote(p, x.r, env)
			deny.Content = append(deny.Content, rule)
		default:
			if by := coveredByAllow(x); by != "" {
				rule = pairs("method", scalar(x.method), "path", scalar(denyGlob(x.glob)))
				rule.HeadComment = x.r.ID + ": " + wouldAsk(x.r) + ", but " + by + " would let it through, so it is denied."
				deny.Content = append(deny.Content, rule)
			}
		}
	}
	addRules(ep, allow, deny)
	return ep
}

// gitRoute is a method and path glob that git smart HTTP or Git LFS uses.
type gitRoute struct{ method, glob string }

// gitRoutes lists the requests that can carry a git rule's operation.
// OpenShell cannot read the ref updates inside a push, so every push
// command shares one route.
func gitRoutes(m *catalog.GitMatch) []gitRoute {
	const repo = "/*/*/"
	switch m.Service + " " + m.Command {
	case decode.GitUploadPack + " " + decode.GitFetch:
		return []gitRoute{{"GET", repo + "info/refs"}, {"POST", repo + "git-upload-pack"}}
	case decode.GitReceivePack + " " + decode.GitListRefs:
		return []gitRoute{{"GET", repo + "info/refs"}, {"POST", repo + "git-receive-pack"}}
	case decode.GitLFS + " " + decode.LFSDownload, decode.GitLFS + " " + decode.LFSUpload:
		return []gitRoute{{"POST", repo + "info/lfs/objects/batch"}}
	case decode.GitLFS + " " + decode.LFSListLocks:
		return []gitRoute{{"GET", repo + "info/lfs/locks"}, {"POST", repo + "info/lfs/locks/verify"}}
	case decode.GitLFS + " " + decode.LFSLock:
		return []gitRoute{{"POST", repo + "info/lfs/locks"}}
	case decode.GitLFS + " " + decode.LFSUnlock:
		return []gitRoute{{"POST", repo + "info/lfs/locks/*/unlock"}}
	case decode.GitReceivePack + " " + decode.GitCreate, decode.GitReceivePack + " " + decode.GitUpdate, decode.GitReceivePack + " " + decode.GitDelete:
		return []gitRoute{{"POST", repo + "git-receive-pack"}}
	}
	return nil
}

// gitEndpoint writes path rules for a git host. Each route gets the strictest
// decision of the rules that share it: a push route is allowed only when
// every kind of ref update would be.
func gitEndpoint(p *policy.Effective, prov *catalog.Provider, rules []*catalog.Rule, host, env string) *yaml.Node {
	ep := endpointHead(host, "", "rest")
	allow, deny := seq(), seq()
	safeDefault := prov.Defaults.RESTSafeMethods != "" && DefaultDecision(p, prov.Defaults.RESTSafeMethods, env) == classes.Allow
	if safeDefault {
		for _, m := range []string{"GET", "HEAD", "OPTIONS"} {
			allow.Content = append(allow.Content, allowRule(pairs("method", scalar(m), "path", scalar("/**"))))
		}
	}
	var order []gitRoute
	decisions := map[gitRoute][]classes.Decision{}
	ids := map[gitRoute][]string{}
	for _, r := range rules {
		if r.Match.Git == nil {
			continue
		}
		for _, rt := range gitRoutes(r.Match.Git) {
			if _, seen := decisions[rt]; !seen {
				order = append(order, rt)
			}
			decisions[rt] = append(decisions[rt], Ceiling(p, r, env))
			ids[rt] = append(ids[rt], r.ID)
		}
	}
	for _, rt := range order {
		rule := pairs("method", scalar(rt.method), "path", scalar(rt.glob))
		safe := safeDefault && rt.method == "GET"
		switch d := classes.Strictest(decisions[rt]...); {
		case d == classes.Allow:
			if !safe {
				allow.Content = append(allow.Content, allowRule(rule))
			}
		case d == classes.Deny:
			rule.HeadComment = "Opfence denies one of " + strings.Join(ids[rt], ", ") + ", which OpenShell cannot tell apart on this path."
			deny.Content = append(deny.Content, rule)
		case safe:
			rule.HeadComment = "Opfence would ask about one of " + strings.Join(ids[rt], ", ") + ", but the GET allow rule above would let it through, so it is denied."
			deny.Content = append(deny.Content, rule)
		}
	}
	addRules(ep, allow, deny)
	return ep
}

func mcpEndpoint(p *policy.Effective, rules []*catalog.Rule, host, path, env string) *yaml.Node {
	ep := endpointHead(host, path, "mcp")
	allow, deny := seq(), seq()
	for _, m := range decode.MCPReadMethods() {
		allow.Content = append(allow.Content, allowRule(pairs("method", scalar(m))))
	}
	var allowed, denied, notes []string
	for _, r := range rules {
		if r.Match.MCP == nil {
			continue
		}
		switch Ceiling(p, r, env) {
		case classes.Allow:
			allowed = append(allowed, r.Match.MCP.Tool)
		case classes.Deny:
			denied = append(denied, r.Match.MCP.Tool)
			if n := argNote(p, r, env); n != "" {
				notes = append(notes, n)
			}
		}
	}
	if len(allowed) > 0 {
		allow.Content = append(allow.Content, allowRule(pairs("method", scalar("tools/call"), "tool", pairs("any", flowSeq(allowed)))))
	}
	if len(denied) > 0 {
		rule := pairs("method", scalar("tools/call"), "tool", pairs("any", flowSeq(denied)))
		rule.HeadComment = strings.Join(notes, "\n")
		deny.Content = append(deny.Content, rule)
	}
	addRules(ep, allow, deny)
	return ep
}

// conditional reports whether r's class depends on its arguments.
func conditional(r *catalog.Rule) bool { return len(r.When) > 0 || r.Classify != nil }

func wouldAsk(r *catalog.Rule) string {
	if conditional(r) {
		return "Opfence would ask for some arguments"
	}
	return "Opfence would ask"
}

// argNote explains a deny that only some arguments call for: OpenShell cannot
// check the arguments, so the whole operation is denied.
func argNote(p *policy.Effective, r *catalog.Rule, env string) string {
	if !conditional(r) {
		return ""
	}
	if d, _ := p.Decide(r.ID, r.Class, env); d == classes.Deny {
		return ""
	}
	var worst []string
	for _, c := range r.PossibleClasses() {
		if d, _ := p.Decide(r.ID, c, env); d == classes.Deny {
			worst = append(worst, string(c))
		}
	}
	return r.ID + ": denied for every request because some arguments make it " + strings.Join(worst, " or ") +
		",\nand OpenShell cannot check arguments."
}

// templateGlob turns a catalog path template into an OpenShell path glob:
// {name} matches one segment (*), a trailing {name*} the rest (**).
func templateGlob(t string) string {
	segs := strings.Split(t, "/")
	for i, s := range segs {
		switch {
		case strings.HasPrefix(s, "{") && strings.HasSuffix(s, "*}"):
			segs[i] = "**"
		case strings.HasPrefix(s, "{") && strings.HasSuffix(s, "}"):
			segs[i] = "*"
		case strings.HasPrefix(s, "{") && strings.Contains(s, "}:"):
			segs[i] = "*" + s[strings.Index(s, "}:")+1:] // {name}:verb
		}
	}
	return strings.Join(segs, "/")
}

// denyGlob widens custom-method segments (*:verb) to * for deny rules. An
// allow glob that a gateway reads more narrowly than meant only blocks more;
// a deny glob must never be read more narrowly, so it does not rely on
// wildcards inside a segment.
func denyGlob(g string) string {
	segs := strings.Split(g, "/")
	for i, s := range segs {
		if strings.HasPrefix(s, "*:") {
			segs[i] = "*"
		}
	}
	return strings.Join(segs, "/")
}

// globsOverlap reports whether some path could match both OpenShell globs
// (segments of literals, * for one segment and a trailing ** for the rest).
func globsOverlap(a, b string) bool {
	as, bs := strings.Split(strings.Trim(a, "/"), "/"), strings.Split(strings.Trim(b, "/"), "/")
	for i := 0; ; i++ {
		switch {
		case i < len(as) && as[i] == "**", i < len(bs) && bs[i] == "**":
			return true
		case i == len(as) || i == len(bs):
			return len(as) == len(bs)
		case !segsOverlap(as[i], bs[i]):
			return false
		}
	}
}

// segsOverlap reports whether one path segment could match both glob
// segments: a literal, * or *:verb (a custom method).
func segsOverlap(a, b string) bool {
	switch {
	case a == "*" || b == "*" || a == b:
		return true
	case strings.HasPrefix(a, "*") && strings.HasPrefix(b, "*"):
		return false // different verbs
	case strings.HasPrefix(b, "*"):
		a, b = b, a
	case !strings.HasPrefix(a, "*"):
		return false // different literals
	}
	return len(b) > len(a)-1 && strings.HasSuffix(b, a[1:])
}

func addRules(ep, allow, deny *yaml.Node) {
	if len(allow.Content) > 0 {
		addPair(ep, "rules", allow)
	}
	if len(deny.Content) > 0 {
		addPair(ep, "deny_rules", deny)
	}
}

func allowRule(m *yaml.Node) *yaml.Node { return pairs("allow", m) }

// YAML node helpers.

func mapping() *yaml.Node { return &yaml.Node{Kind: yaml.MappingNode} }
func seq() *yaml.Node     { return &yaml.Node{Kind: yaml.SequenceNode} }

func scalar(s string) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: s}
}

func flowSeq(items []string) *yaml.Node {
	n := &yaml.Node{Kind: yaml.SequenceNode, Style: yaml.FlowStyle}
	for _, s := range items {
		n.Content = append(n.Content, scalar(s))
	}
	return n
}

func addPair(m *yaml.Node, k string, v *yaml.Node) { m.Content = append(m.Content, scalar(k), v) }

func pairs(kv ...any) *yaml.Node {
	m := mapping()
	for i := 0; i < len(kv); i += 2 {
		addPair(m, kv[i].(string), kv[i+1].(*yaml.Node))
	}
	return m
}
